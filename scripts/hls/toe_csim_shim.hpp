// =============================================================================
// toe_csim_shim.hpp -- мостик toe() -> toe_core<DATA_WIDTH>() для csim
// =============================================================================
//
// ЗАЧЕМ. Апстримный toe_tb.cpp вызывает toe(...), но в toe.hpp объявлена ТОЛЬКО
// toe_core (:175). Сама toe() определена в toe.cpp (:826), однако в заголовок не
// выведена, поэтому тестбенч её не видит: "use of undeclared identifier 'toe'".
// Плюс типы разные -- toe() принимает ap_axiu, а тестбенч объявляет ipRxData как
// stream<net_axis<DATA_WIDTH>> (toe_tb.cpp:575), то есть ровно то, что ждёт
// toe_core. Тестбенч написан под toe_core, и штатный run_hls.csim.tcl со своим
// `set_top toe` не мог работать никогда.
//
// ПОДКЛЮЧАЕТСЯ ЧЕРЕЗ -include, А НЕ #include. Апстримный toe_tb.cpp не тронут:
// clang вставляет этот заголовок перед первой строкой файла, как если бы
// #include стоял там сам. См. OUR_FLAGS в run_toe_csim.tcl.
//
// ДВЕ ПРОВАЛИВШИЕСЯ ПОПЫТКИ ДО ЭТОГО, чтобы не повторять:
//   1. -Dtoe=toe_core<DATA_WIDTH> -- угловые скобки доходят до shell, который
//      видит '<' как редирект: "cannot open DATA_WIDTH: No such file".
//   2. Отдельный .cpp с определением toe() -- у toe_tb.cpp своя единица
//      трансляции, объявления до вызова нет, ошибка та же.
//
// ШАБЛОН ВМЕСТО 30 ЯВНЫХ ТИПОВ. Аргументов у toe_core тридцать. Выписывать их
// руками -- тридцать шансов молча разойтись с заголовком: неверный тип дал бы
// либо ошибку компиляции (это ещё повезло), либо неявное приведение и неверное
// поведение csim, которое я приму за поведение железа. Variadic-шаблон
// перебрасывает ровно то, что пришло, а типы проверяет компилятор против
// настоящего объявления toe_core.

#ifndef TOE_CSIM_SHIM_HPP
#define TOE_CSIM_SHIM_HPP

#include "toe.hpp"

template <typename... Args>
void toe(Args&... args)
{
     toe_core<DATA_WIDTH>(args...);
}

#endif
