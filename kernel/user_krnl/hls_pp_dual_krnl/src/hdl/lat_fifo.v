// =============================================================================
// lat_fifo -- FIFO измерений задержки, читается хостом по одному слову
// =============================================================================
//
// ЗАЧЕМ ИМЕННО FIFO, А НЕ РЕГИСТРЫ.
//
// В probe-ядре четыре таймстемпа лежали в простых регистрах и перезаписывались
// каждым пакетом. Годилось: хост сам отправлял по одному пакету и сразу читал.
//
// Здесь клиент (ppclient) гонит пакеты подряд без остановки. Одно чтение по
// JTAG -- десятки миллисекунд, за это время пройдут сотни пакетов, и регистр
// покажет случайный из них. Собрать статистику так нельзя.
//
// ПОЧЕМУ ГЛУБИНА 128, А НЕ 512 И НЕ 4096.
//
// Задача -- сотня измерений (ppclient -count 100), не десятки тысяч. 128
// записей покрывают это с запасом и стоят одну BRAM-плитку. Больше не нужно:
// JTAG всё равно вычитывает порядка сотен слов в секунду, и 4096 записей
// читались бы минуту.
//
// ПОВЕДЕНИЕ ПРИ ПЕРЕПОЛНЕНИИ: НОВЫЕ ЗАПИСИ ОТБРАСЫВАЮТСЯ, СТАРЫЕ ЦЕЛЫ.
//
// Ровно то, о чём была просьба -- "чтобы это фифо нормально сработало, без
// переключений". Альтернатива (затирать старые по кругу) дала бы окно "хвост
// прогона", но при переполнении в момент чтения хост увидел бы смесь: часть
// записей от начала, часть от конца, и по номерам это не восстановить.
//
// Отброшенные считаются в overflow. Хост видит: если overflow > 0, значит
// пакетов было больше, чем 128, и выборка -- НАЧАЛО прогона, а не весь он.
// Молча терять нельзя: невидимая потеря выглядит как "измерили всё".
//
// ЧТО ЛЕЖИТ В ОДНОЙ ЗАПИСИ. Три дельты по 10 бит + флаг:
//
//     [9:0]    STACK_RX   T2 -> t2   приём: CMAC-край -> ядро
//     [19:10]  KERNEL     t2 -> t1   ядро: принял -> отдал
//     [29:20]  STACK_TX   t1 -> T1   передача: ядро -> CMAC-край
//     [30]     valid_all  все три дельты корректны
//     [31]     saturated  хотя бы одна дельта не влезла в 10 бит
//
// ПОЧЕМУ 10 БИТ НА ДЕЛЬТУ. 1023 такта при 165 МГц = 6.2 мкс. По оценке бюджета
// (docs, toe-latency-budget-estimate) весь гейтвей -- 1.0-1.8 мкс, то есть
// 165-300 тактов. Запас втрое. Дельта больше 1023 означает не "медленно", а
// "потеряли пару" -- и это надо видеть отдельным флагом, а не как большое
// число, которое усреднится с нормальными.
//
// Три дельты в одном 32-битном слове -- чтобы хост читал ОДИН регистр на
// измерение, а не три. По JTAG каждое чтение стоит миллисекунды.
`timescale 1ns / 1ps
`default_nettype none

module lat_fifo #(
     parameter integer DEPTH_LOG2 = 7      // 128 записей
)(
     input  wire        ap_clk,
     input  wire        ap_rst_n,

     // запись: строб + данные, одна запись за такт
     input  wire        wr_en,
     input  wire [31:0] wr_data,

     // сброс содержимого от хоста (запись 1 в регистр очистки)
     input  wire        clear,

     // чтение: хост читает rd_data, потом дёргает rd_pop на один такт
     input  wire        rd_pop,
     output wire [31:0] rd_data,

     // состояние для хоста
     output wire [31:0] count,      // сколько записей лежит
     output wire [31:0] overflow,   // сколько отброшено из-за полного FIFO
     output wire        empty,
     output wire        full
);
     localparam integer DEPTH = 1 << DEPTH_LOG2;

     // BRAM-массив. BIND_STORAGE тут не нужен -- Vivado сам выберет BRAM для
     // 128x32; при меньшей глубине выбрал бы распределённую память, и это тоже
     // было бы верно.
     reg [31:0] mem [0:DEPTH-1];

     reg [DEPTH_LOG2-1:0] wr_ptr;
     reg [DEPTH_LOG2-1:0] rd_ptr;
     reg [DEPTH_LOG2:0]   cnt;        // на бит шире указателей: вмещает DEPTH
     reg [31:0]           ovf;

     assign empty    = (cnt == 0);
     assign full     = (cnt == DEPTH);
     assign count    = {{(32-DEPTH_LOG2-1){1'b0}}, cnt};
     assign overflow = ovf;

     // Чтение асинхронное по адресу: хост читает регистр, значение уже готово,
     // и rd_pop только сдвигает указатель. Синхронное чтение потребовало бы
     // от хоста двух обращений (задать адрес, потом прочитать) -- лишний
     // JTAG-цикл на каждое измерение.
     assign rd_data = mem[rd_ptr];

     // Запись и чтение в одном always: указатели и cnt меняются вместе, и
     // разнеся их по двум блокам, легко получить гонку на cnt при
     // одновременных wr_en и rd_pop.
     //
     // ПОРЯДОК И УСЛОВИЯ ВЕТВЕЙ ПРОДУБЛИРОВАНЫ в модели
     // src/hdl/tb/test_lat_fifo.py (класс LatFifo.tick). Правя здесь --
     // правьте там же: тест сверяет поведение с моделью, и разойдясь, он
     // начнёт проверять не этот код. Локального xvlog нет, модель -- всё,
     // что есть до сборочной машины.
     //
     // Два дефекта эта модель уже нашла: молчаливую потерю записи при
     // full+rd_pop (см. третью ветвь) и неверное извлечение поля в самом
     // тесте.
     always @(posedge ap_clk) begin
          if (~ap_rst_n || clear) begin
               wr_ptr <= {DEPTH_LOG2{1'b0}};
               rd_ptr <= {DEPTH_LOG2{1'b0}};
               cnt    <= {(DEPTH_LOG2+1){1'b0}};
               // ovf НЕ сбрасывается по clear: хост чистит FIFO между
               // прогонами, а счётчик потерь должен пережить чистку -- иначе
               // потери прошлого прогона исчезнут вместе с данными.
               if (~ap_rst_n) ovf <= 32'd0;
          end else begin
               // Порядок веток важен. Одновременные wr_en и rd_pop -- обычное
               // дело (хост читает, пока идут пакеты), и тогда cnt не
               // меняется, а оба указателя сдвигаются.
               if (wr_en && !full && rd_pop && !empty) begin
                    mem[wr_ptr] <= wr_data;
                    wr_ptr <= wr_ptr + 1'b1;
                    rd_ptr <= rd_ptr + 1'b1;
                    // cnt без изменений
               end else if (wr_en && !full) begin
                    mem[wr_ptr] <= wr_data;
                    wr_ptr <= wr_ptr + 1'b1;
                    cnt    <= cnt + 1'b1;
               end else if (rd_pop && !empty) begin
                    rd_ptr <= rd_ptr + 1'b1;
                    cnt    <= cnt - 1'b1;
                    // ЗАПИСЬ В ЭТОМ ТАКТЕ ОТБРАСЫВАЕТСЯ, И ЕЁ НАДО ЗАСЧИТАТЬ.
                    //
                    // Сюда попадаем при full && rd_pop: место освобождается в
                    // этом же такте, но писать одновременно нельзя -- при
                    // wr_ptr == rd_ptr это чтение и запись одной ячейки BRAM,
                    // то есть неопределённое значение на выходе. Отбрасываем.
                    //
                    // Тест test_lat_fifo.py сценарий 7 нашёл, что первая
                    // версия теряла эту запись МОЛЧА: ovf не увеличивался,
                    // потому что до ветви ниже управление не доходило. Хост
                    // видел бы 128 записей вместо 129 и никакого признака
                    // потери -- ровно то, чего нельзя допускать.
                    if (wr_en) ovf <= ovf + 32'd1;
               end else if (wr_en) begin
                    // full && !rd_pop: полное FIFO, хост не читает.
                    // Новое отбрасываем, старое цело.
                    ovf <= ovf + 32'd1;
               end
          end
     end
endmodule

`default_nettype wire
