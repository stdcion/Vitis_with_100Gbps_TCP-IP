// =============================================================================
// lat_fifo -- FIFO измерений задержки, читается хостом по одному слову
// =============================================================================
//
// ЗАЧЕМ ИМЕННО FIFO, А НЕ РЕГИСТРЫ.
//
// В probe-ядре четыре таймстемпа лежали в простых регистрах и перезаписывались
// каждым пакетом. Годилось: хост сам отправлял по одному пакету и сразу читал.
//
// Здесь клиент (ppclient) гонит пакеты подряд без остановки. Одно чтение по
// JTAG -- десятки миллисекунд, за это время пройдут сотни пакетов, и регистр
// покажет случайный из них. Собрать статистику так нельзя.
//
// ПОЧЕМУ ГЛУБИНА 512 СЛОВ.
//
// Задача -- сотня измерений (ppclient -count 100), не десятки тысяч. Четыре
// метки на измерение дают 128 измерений при 512 словах: сотня покрыта с
// запасом, стоит одну BRAM-плитку. Больше не нужно -- JTAG вычитывает порядка
// сотен слов в секунду, и уже 512 слов читаются единицы секунд.
//
// ПОВЕДЕНИЕ ПРИ ПЕРЕПОЛНЕНИИ: НОВЫЕ ЗАПИСИ ОТБРАСЫВАЮТСЯ, СТАРЫЕ ЦЕЛЫ.
//
// Ровно то, о чём была просьба -- "чтобы это фифо нормально сработало, без
// переключений". Альтернатива (затирать старые по кругу) дала бы окно "хвост
// прогона", но при переполнении в момент чтения хост увидел бы смесь: часть
// записей от начала, часть от конца, и по номерам это не восстановить.
//
// Отброшенные считаются в overflow. Хост видит: если overflow > 0, значит
// пакетов было больше, чем 128, и выборка -- НАЧАЛО прогона, а не весь он.
// Молча терять нельзя: невидимая потеря выглядит как "измерили всё".
//
// ЧТО ЛЕЖИТ В ОДНОЙ ЗАПИСИ: ЧЕТЫРЕ СЫРЫЕ МЕТКИ ВРЕМЕНИ, БЕЗ АРИФМЕТИКИ.
//
//     T2   кадр пришёл на axis_net_rx  (край CMAC -> стек)
//     t2   payload дошёл до ядра       (rx_data.tlast)
//     t1   ядро отдало payload         (tx_data.tlast)
//     T1   кадр ушёл на axis_net_tx    (стек -> край CMAC)
//
// Каждая -- полное 32-битное значение общего счётчика тактов, то есть четыре
// слова FIFO на одно измерение.
//
// ПОЧЕМУ НЕ ДЕЛЬТЫ, ХОТЯ ЭТО БЫЛО БЫ В ЧЕТЫРЕ РАЗА КОМПАКТНЕЕ.
//
// Первая версия считала три дельты в железе и упаковывала их в одно слово по
// 10 бит. Отвергнуто: вычитание в железе СКРЫВАЕТ сырые числа, а с ними --
// возможность проверить саму арифметику. У probe-ядра то же решение принято
// в epd_raw (jtag_ctrl.tcl): "callers that only want the intervals can still
// lrange them out, and nothing silently discards the raw data", и колонка
// status с флагом TORN ловит рассогласование сложением интервалов.
//
// Здесь тот же приём доступен только при сырых метках: если
// (t2-T2) + (t1-t2) + (T1-t1) != (T1-T2), значит какая-то метка от другого
// пакета. С готовыми дельтами это не проверить -- их сумма сойдётся всегда.
//
// Плюс дельты теряли переполнение счётчика и требовали флага saturated.
// Сырые метки от этого свободны: разность 32-битных значений верна и при
// переходе через ноль.
//
// ЦЕНА: четыре слова вместо одного, то есть 128 записей = 32 измерения.
// При задаче "сотня пакетов" этого мало, поэтому DEPTH_LOG2 = 9 (512 слов =
// 128 измерений). Одна BRAM-плитка всё ещё хватает.
`timescale 1ns / 1ps
`default_nettype none

module lat_fifo #(
     // 512 слов = 128 измерений по четыре метки. Больше не нужно: JTAG
     // вычитывает порядка сотен слов в секунду, и 128 измерений -- это уже
     // 512 чтений, единицы секунд.
     parameter integer DEPTH_LOG2 = 9
)(
     input  wire        ap_clk,
     input  wire        ap_rst_n,

     // ЗАПИСЬ ЧЕТВЁРКОЙ, А НЕ ПО ОДНОМУ СЛОВУ.
     //
     // Четыре метки одного измерения обязаны лечь ВМЕСТЕ или не лечь совсем.
     // При записи по одному слову хватило бы FIFO, заполнившегося после
     // второй метки: две легли, две отброшены, и хост получил бы кадр,
     // склеенный из двух пакетов -- с виду правдоподобный, но бессмысленный.
     //
     // Поэтому вход широкий, а места проверяется сразу на четыре слова.
     // Либо всё измерение, либо ничего.
     input  wire         wr_en,
     input  wire [127:0] wr_data,   // {T1, t1, t2, T2} -- порядок как в шапке

     // сброс содержимого от хоста (запись 1 в регистр очистки)
     input  wire        clear,

     // чтение: хост читает rd_data, потом дёргает rd_pop на один такт
     input  wire        rd_pop,
     output wire [31:0] rd_data,

     // состояние для хоста
     output wire [31:0] count,      // сколько СЛОВ лежит (измерений = count/4)
     output wire [31:0] overflow,   // сколько ИЗМЕРЕНИЙ отброшено
     output wire        empty,
     output wire        full
);
     localparam integer DEPTH = 1 << DEPTH_LOG2;

     // BRAM-массив. BIND_STORAGE тут не нужен -- Vivado сам выберет BRAM для
     // 128x32; при меньшей глубине выбрал бы распределённую память, и это тоже
     // было бы верно.
     reg [31:0] mem [0:DEPTH-1];

     reg [DEPTH_LOG2-1:0] wr_ptr;
     reg [DEPTH_LOG2-1:0] rd_ptr;
     reg [DEPTH_LOG2:0]   cnt;        // на бит шире указателей: вмещает DEPTH
     reg [31:0]           ovf;

     assign empty    = (cnt == 0);
     assign full     = (cnt == DEPTH);
     assign count    = {{(32-DEPTH_LOG2-1){1'b0}}, cnt};
     assign overflow = ovf;

     // Чтение асинхронное по адресу: хост читает регистр, значение уже готово,
     // и rd_pop только сдвигает указатель. Синхронное чтение потребовало бы
     // от хоста двух обращений (задать адрес, потом прочитать) -- лишний
     // JTAG-цикл на каждое измерение.
     assign rd_data = mem[rd_ptr];

     // Места хватает на всё измерение? Проверка ИМЕННО НА ЧЕТЫРЕ слова:
     // при трёх свободных запись не начинается вовсе, а не кладёт три метки
     // из четырёх.
     wire room4 = (cnt <= DEPTH - 4);

     // Запись и чтение в одном always: указатели и cnt меняются вместе, и
     // разнеся их по двум блокам, легко получить гонку на cnt при
     // одновременных wr_en и rd_pop.
     //
     // ПОРЯДОК И УСЛОВИЯ ВЕТВЕЙ ПРОДУБЛИРОВАНЫ в модели
     // src/hdl/tb/test_lat_fifo.py (класс LatFifo.tick). Правя здесь --
     // правьте там же: тест сверяет поведение с моделью, и разойдясь, он
     // начнёт проверять не этот код. Локального xvlog нет, модель -- всё,
     // что есть до сборочной машины.
     //
     // Дефекты, которые эта модель уже нашла: молчаливая потеря записи при
     // полном FIFO с одновременным чтением, и неверное извлечение поля в
     // самом тесте.
     always @(posedge ap_clk) begin
          if (~ap_rst_n || clear) begin
               wr_ptr <= {DEPTH_LOG2{1'b0}};
               rd_ptr <= {DEPTH_LOG2{1'b0}};
               cnt    <= {(DEPTH_LOG2+1){1'b0}};
               // ovf НЕ сбрасывается по clear: хост чистит FIFO между
               // прогонами, а счётчик потерь должен пережить чистку -- иначе
               // потери прошлого прогона исчезнут вместе с данными.
               if (~ap_rst_n) ovf <= 32'd0;
          end else begin
               // Четыре слова за такт. Все четыре ячейки пишутся сразу --
               // это четыре порта записи в BRAM, чего в одной плитке нет,
               // поэтому Vivado разложит массив на четыре банка по 128 слов.
               // Так и надо: банки независимы, конфликта портов не будет.
               // Четыре присваивания в развёрнутом виде, а не через for.
               //
               // Цикл с индексом-integer требовал бы среза k[DEPTH_LOG2-1:0]
               // для сложения с указателем -- срез от integer незаконен, и
               // xvlog отверг бы это, хотя синтез, возможно, проглотил бы
               // (см. память: xvlog строже synth). Четыре строки читаются
               // не хуже и не имеют этой ловушки.
               if (wr_en && room4) begin
                    mem[wr_ptr + 0] <= wr_data[31:0];     // T2
                    mem[wr_ptr + 1] <= wr_data[63:32];    // t2
                    mem[wr_ptr + 2] <= wr_data[95:64];    // t1
                    mem[wr_ptr + 3] <= wr_data[127:96];   // T1
                    wr_ptr <= wr_ptr + 4;
               end

               // Счётчик слов: +4 за запись, -1 за чтение, и оба могут
               // случиться в одном такте. Литералы без ширины -- иначе
               // 3'd4 обрезалось бы до нуля (4 не влезает в три бита).
               if (wr_en && room4 && rd_pop && !empty)
                    cnt <= cnt + 3;                    // +4 -1
               else if (wr_en && room4)
                    cnt <= cnt + 4;
               else if (rd_pop && !empty)
                    cnt <= cnt - 1;

               if (rd_pop && !empty)
                    rd_ptr <= rd_ptr + 1'b1;

               // ПОТЕРЯ СЧИТАЕТСЯ ВСЕГДА, КОГДА ЗАПИСЬ НЕ ПРОШЛА.
               //
               // Отдельным условием, а не веткой else внутри цепочки выше:
               // в первой версии потеря при полном FIFO с одновременным
               // чтением НЕ засчитывалась -- управление до нужной ветки не
               // доходило, и хост видел меньше измерений без признака потери.
               // Здесь условие ровно одно: строб был, места не было.
               if (wr_en && !room4)
                    ovf <= ovf + 32'd1;
          end
     end
endmodule

`default_nettype wire
