// =============================================================================
// lat_fifo -- FIFO измерений задержки, читается хостом по одному слову
// =============================================================================
//
// ЗАЧЕМ ИМЕННО FIFO, А НЕ РЕГИСТРЫ.
//
// В probe-ядре четыре таймстемпа лежали в простых регистрах и перезаписывались
// каждым пакетом. Годилось: хост сам отправлял по одному пакету и сразу читал.
//
// Здесь клиент (ppclient) гонит пакеты подряд без остановки. Одно чтение по
// JTAG -- десятки миллисекунд, за это время пройдут сотни пакетов, и регистр
// покажет случайный из них. Собрать статистику так нельзя.
//
// ПОЧЕМУ ГЛУБИНА 512 СЛОВ.
//
// Задача -- сотня измерений (ppclient -count 100), не десятки тысяч. Четыре
// метки на измерение дают 128 измерений при 512 словах: сотня покрыта с
// запасом, стоит одну BRAM-плитку. Больше не нужно -- JTAG вычитывает порядка
// сотен слов в секунду, и уже 512 слов читаются единицы секунд.
//
// ПОВЕДЕНИЕ ПРИ ПЕРЕПОЛНЕНИИ: НОВЫЕ ЗАПИСИ ОТБРАСЫВАЮТСЯ, СТАРЫЕ ЦЕЛЫ.
//
// Ровно то, о чём была просьба -- "чтобы это фифо нормально сработало, без
// переключений". Альтернатива (затирать старые по кругу) дала бы окно "хвост
// прогона", но при переполнении в момент чтения хост увидел бы смесь: часть
// записей от начала, часть от конца, и по номерам это не восстановить.
//
// Отброшенные считаются в overflow. Хост видит: если overflow > 0, значит
// пакетов было больше, чем 128, и выборка -- НАЧАЛО прогона, а не весь он.
// Молча терять нельзя: невидимая потеря выглядит как "измерили всё".
//
// ЧТО ЛЕЖИТ В ОДНОЙ ЗАПИСИ: ЧЕТЫРЕ СЫРЫЕ МЕТКИ ВРЕМЕНИ, БЕЗ АРИФМЕТИКИ.
//
//     T2   кадр пришёл на axis_net_rx  (край CMAC -> стек)
//     t2   payload дошёл до ядра       (rx_data.tlast)
//     t1   ядро отдало payload         (tx_data.tlast)
//     T1   кадр ушёл на axis_net_tx    (стек -> край CMAC)
//
// Каждая -- полное 32-битное значение общего счётчика тактов, то есть четыре
// слова FIFO на одно измерение.
//
// ПОЧЕМУ НЕ ДЕЛЬТЫ, ХОТЯ ЭТО БЫЛО БЫ В ЧЕТЫРЕ РАЗА КОМПАКТНЕЕ.
//
// Первая версия считала три дельты в железе и упаковывала их в одно слово по
// 10 бит. Отвергнуто: вычитание в железе СКРЫВАЕТ сырые числа, а с ними --
// возможность проверить саму арифметику. У probe-ядра то же решение принято
// в epd_raw (jtag_ctrl.tcl): "callers that only want the intervals can still
// lrange them out, and nothing silently discards the raw data", и колонка
// status с флагом TORN ловит рассогласование сложением интервалов.
//
// Здесь тот же приём доступен только при сырых метках: если
// (t2-T2) + (t1-t2) + (T1-t1) != (T1-T2), значит какая-то метка от другого
// пакета. С готовыми дельтами это не проверить -- их сумма сойдётся всегда.
//
// Плюс дельты теряли переполнение счётчика и требовали флага saturated.
// Сырые метки от этого свободны: разность 32-битных значений верна и при
// переходе через ноль.
//
// ЦЕНА: четыре слова вместо одного, то есть DEPTH/4 измерений.
// DEPTH_LOG2 = 9 даёт 512 слов = 128 измерений -- сотня с запасом.
//
// ЗАПИСЬ РАСТЯНУТА НА ЧЕТЫРЕ ТАКТА, А НЕ В ОДИН, И ЭТО ВЫНУЖДЕННО.
//
// Первая версия писала все четыре слова одновременно:
//     mem[wr_ptr+0] <= ...; mem[wr_ptr+1] <= ...;  и так далее
// Это четыре порта записи плюс асинхронное чтение -- пять портов к одному
// массиву. Такой памяти в FPGA нет: BRAM даёт два порта и СИНХРОННОЕ чтение,
// distributed RAM -- один порт записи. Vivado либо размножил бы массив в
// четыре копии (16x расход LUT-памяти на 512x32), либо отказал.
//
// Поэтому измерение принимается за один такт в РЕГИСТР (128 бит), а в память
// уходит по слову за такт из него. Четыре такта на измерение -- при пакетах
// раз в микросекунды (165+ тактов) запас огромный.
//
// АТОМАРНОСТЬ ОТ ЭТОГО НЕ СТРАДАЕТ: место проверяется на все четыре слова В
// МОМЕНТ ПРИЁМА, и если его нет -- измерение не принимается вовсе. Частично
// записанных четвёрок не бывает.
`timescale 1ns / 1ps
`default_nettype none

module lat_fifo #(
     // 512 слов = 128 измерений по четыре метки. Больше не нужно: JTAG
     // вычитывает порядка сотен слов в секунду, и 128 измерений -- это уже
     // 512 чтений, единицы секунд.
     parameter integer DEPTH_LOG2 = 9
)(
     input  wire        ap_clk,
     input  wire        ap_rst_n,

     // ЗАПИСЬ ЧЕТВЁРКОЙ, А НЕ ПО ОДНОМУ СЛОВУ.
     //
     // Четыре метки одного измерения обязаны лечь ВМЕСТЕ или не лечь совсем.
     // При записи по одному слову хватило бы FIFO, заполнившегося после
     // второй метки: две легли, две отброшены, и хост получил бы кадр,
     // склеенный из двух пакетов -- с виду правдоподобный, но бессмысленный.
     //
     // Поэтому вход широкий, а места проверяется сразу на четыре слова.
     // Либо всё измерение, либо ничего.
     input  wire         wr_en,
     input  wire [127:0] wr_data,   // {T1, t1, t2, T2} -- порядок как в шапке

     // сброс содержимого от хоста (запись 1 в регистр очистки)
     input  wire        clear,

     // чтение: хост читает rd_data, потом дёргает rd_pop на один такт
     input  wire        rd_pop,
     output wire [31:0] rd_data,

     // состояние для хоста
     output wire [31:0] count,      // сколько СЛОВ лежит (измерений = count/4)
     output wire [31:0] overflow,   // сколько ИЗМЕРЕНИЙ отброшено
     output wire        empty,
     output wire        full
);
     localparam integer DEPTH = 1 << DEPTH_LOG2;

     // ФОРМА ВЗЯТА ИЗ РАБОТАЮЩЕГО FIFO, СГЕНЕРИРОВАННОГО HLS.
     //
     // Эталон -- hls_dual_echo_krnl_fifo_w16_d512_A.v из de_rtl.tgz: тот же
     // размер (512 слов), прошёл синтез и имплементацию на этой плате. Он
     // делает ровно три вещи, и все три здесь повторены:
     //
     //   (* ram_style = ... *)   явное указание ресурса, а не на усмотрение
     //   одна запись за такт     mem[waddr] <= din под if (we)
     //   чтение через регистр    mem_reg <= mem[raddr]; assign dout = mem_reg
     //
     // ram_style="block" вместо "auto" у HLS: у нас 512x32 = 16 Кбит, это
     // ровно под BRAM18, и оставлять выбор эвристике незачем. При "auto"
     // Vivado иногда раскладывает такое в distributed RAM -- сотни LUT там,
     // где хватает одной плитки, и это заметно на SLR1, который у нас уже
     // узкое место (память: u200-slr1-is-the-bottleneck).
     (* ram_style = "block" *)
     reg [31:0] mem [0:DEPTH-1];

     reg [DEPTH_LOG2-1:0] wr_ptr;
     reg [DEPTH_LOG2-1:0] rd_ptr;
     reg [DEPTH_LOG2:0]   cnt;        // на бит шире указателей: вмещает DEPTH
     reg [31:0]           ovf;

     assign empty    = (cnt == 0);
     assign full     = (cnt == DEPTH);
     assign count    = {{(32-DEPTH_LOG2-1){1'b0}}, cnt};
     assign overflow = ovf;

     // ЧТЕНИЕ СИНХРОННОЕ -- иначе это не BRAM.
     //
     // Первая версия писала assign rd_data = mem[rd_ptr] (асинхронно). У BRAM
     // асинхронного порта чтения нет вообще; Vivado разложил бы массив в
     // distributed RAM на LUT, и 512x32 стоило бы сотни LUT вместо одной
     // BRAM-плитки.
     //
     // Регистр на выходе не усложняет протокол для хоста: значение появляется
     // через такт после смены rd_ptr, а между чтением по JTAG и предыдущим
     // pop проходят тысячи тактов. То есть к моменту чтения rd_data уже
     // готово.
     reg [31:0] rd_data_q;
     always @(posedge ap_clk) begin
          rd_data_q <= mem[rd_ptr];
     end
     assign rd_data = rd_data_q;

     // ЧИТАЕМ КАЖДЫЙ ТАКТ, БЕЗ if (rden) -- отличие от эталона HLS, и оно
     // осознанное. У HLS чтение под условием, потому что там FIFO в тракте
     // данных и лишнее обращение к BRAM стоит энергии. Здесь FIFO читает
     // ТОЛЬКО хост по JTAG, раз в миллисекунды: постоянное чтение проще (нет
     // сигнала rden, нечему разъехаться) и гарантирует, что к моменту
     // обращения хоста значение уже готово.

     // ── приём измерения в регистр ────────────────────────────────────────
     //
     // Место проверяется здесь и только здесь: если четырёх слов нет,
     // измерение не принимается. Уже начатую выгрузку новое измерение не
     // прерывает -- busy держит приём.
     reg [127:0] wr_shift;
     reg [2:0]   wr_left;      // сколько слов осталось выгрузить (0..4)
     wire        busy  = (wr_left != 3'd0);
     wire        room4 = (cnt <= DEPTH - 4);
     wire        accept = wr_en & room4 & ~busy;

     // Строб потери: место было, но мы ещё выгружаем прошлое -- или места нет.
     // Оба случая надо считать, иначе хост увидит меньше измерений без
     // признака потери.
     wire        reject = wr_en & (~room4 | busy);

     // ── запись и чтение ──────────────────────────────────────────────────
     //
     // ПОРЯДОК И УСЛОВИЯ ПРОДУБЛИРОВАНЫ в модели src/hdl/tb/test_lat_fifo.py
     // (класс LatFifo). Правя здесь -- правьте там же: тест сверяет поведение
     // с моделью, и разойдясь, он начнёт проверять не этот код. Локального
     // xvlog нет, модель -- всё, что есть до сборочной машины.
     always @(posedge ap_clk) begin
          if (~ap_rst_n || clear) begin
               wr_ptr   <= {DEPTH_LOG2{1'b0}};
               rd_ptr   <= {DEPTH_LOG2{1'b0}};
               cnt      <= {(DEPTH_LOG2+1){1'b0}};
               wr_left  <= 3'd0;
               wr_shift <= 128'd0;
               // ovf НЕ сбрасывается по clear: хост чистит FIFO между
               // прогонами, а счётчик потерь должен пережить чистку -- иначе
               // потери прошлого прогона исчезнут вместе с данными.
               if (~ap_rst_n) ovf <= 32'd0;
          end else begin
               // Приём: защёлкиваем все четыре метки и заводим выгрузку.
               if (accept) begin
                    wr_shift <= wr_data;
                    wr_left  <= 3'd4;
               end

               // Выгрузка: одно слово за такт, младшее вперёд (T2, t2, t1, T1).
               if (busy) begin
                    mem[wr_ptr] <= wr_shift[31:0];
                    wr_shift    <= {32'd0, wr_shift[127:32]};
                    wr_ptr      <= wr_ptr + 1;
                    wr_left     <= wr_left - 1;
               end

               // Счётчик слов. Выгрузка и чтение могут совпасть в одном такте.
               if (busy && rd_pop && !empty)
                    cnt <= cnt;                  // +1 -1
               else if (busy)
                    cnt <= cnt + 1;
               else if (rd_pop && !empty)
                    cnt <= cnt - 1;

               if (rd_pop && !empty)
                    rd_ptr <= rd_ptr + 1;

               // Потеря считается ОДНИМ условием -- и это тот случай, который
               // первая версия теряла молча: до нужной ветви цепочки if/else
               // управление не доходило, и хост видел меньше измерений без
               // всякого признака.
               if (reject)
                    ovf <= ovf + 32'd1;
          end
     end
endmodule

`default_nettype wire
