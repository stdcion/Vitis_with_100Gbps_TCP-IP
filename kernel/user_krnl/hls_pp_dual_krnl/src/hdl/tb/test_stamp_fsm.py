#!/usr/bin/env python3
# =============================================================================
# test_stamp_fsm.py -- модель автомата сбора измерения из обёртки
# =============================================================================
#
# ЗАЧЕМ. Автомат склеивает четыре метки в одно измерение, и главный риск --
# СКЛЕЙКА МЕТОК ОТ РАЗНЫХ ПАКЕТОВ. Она даёт правдоподобное, но ложное число:
# дельты положительны, сумма сходится, а измерение бессмысленно. Ни csynth, ни
# глаз такое не поймают -- нужен прогон по сценариям.
#
# Локального xvlog нет (Vitis на сборочной машине), поэтому модель. Она
# повторяет case из hls_pp_dual_krnl_wrapper.sv дословно: при правке .sv
# правится и здесь, иначе тест проверяет не тот код.
#
# ЗАПУСК:  python3 test_stamp_fsm.py

import sys

WAIT_T2, WAIT_t2, WAIT_t1, WAIT_T1 = range(4)


class StampFsm:
    """Копия always_ff из обёртки. Ветви и порядок -- те же."""

    def __init__(self):
        self.st = WAIT_T2
        self.T2 = self.t2 = self.t1 = 0
        self.dropped = 0
        self.out = []          # готовые измерения (T2, t2, t1, T1)

    def tick(self, clk, T2=False, t2=False, t1=False, T1=False):
        """clk -- текущее значение cycle_counter."""
        if self.st == WAIT_T2:
            if T2:
                self.T2 = clk
                self.st = WAIT_t2

        elif self.st == WAIT_t2:
            if T2:
                # Новый пакет догнал: прошлое измерение порвано.
                self.T2 = clk
                self.dropped += 1
            elif t2:
                self.t2 = clk
                self.st = WAIT_t1

        elif self.st == WAIT_t1:
            if T2:
                self.T2 = clk
                self.st = WAIT_t2
                self.dropped += 1
            elif t1:
                self.t1 = clk
                self.st = WAIT_T1

        elif self.st == WAIT_T1:
            if T1:
                # Измерение готово. T1 берётся прямо со счётчика.
                self.out.append((self.T2, self.t2, self.t1, clk))
                if T2:
                    # Следующий запрос вошёл в том же такте -- подхватываем,
                    # иначе он потерялся бы.
                    self.T2 = clk
                    self.st = WAIT_t2
                else:
                    self.st = WAIT_T2
            elif T2:
                self.T2 = clk
                self.st = WAIT_t2
                self.dropped += 1


fails = 0


def check(cond, what):
    global fails
    if cond:
        print("  [ OK ] " + what)
    else:
        print("  [FAIL] " + what)
        fails += 1


def consistent(m):
    T2, t2, t1, T1 = m
    return (t2 - T2) + (t1 - t2) + (T1 - t1) == (T1 - T2)


# ---------------------------------------------------------------------------
print("[1] один пакет: четыре метки по порядку")
f = StampFsm()
f.tick(100, T2=True)
f.tick(140, t2=True)
f.tick(150, t1=True)
f.tick(190, T1=True)
check(len(f.out) == 1, "одно измерение готово")
check(f.out[0] == (100, 140, 150, 190), "метки те, что подавали")
check(consistent(f.out[0]), "согласовано")
check(f.dropped == 0, "ничего не порвалось")

# ---------------------------------------------------------------------------
print("\n[2] серия из 10 пакетов подряд")
f = StampFsm()
for i in range(10):
    b = 1000 + i * 500
    f.tick(b, T2=True)
    f.tick(b + 40, t2=True)
    f.tick(b + 50, t1=True)
    f.tick(b + 90, T1=True)
check(len(f.out) == 10, "10 измерений")
check(all(consistent(m) for m in f.out), "все согласованы")
check(f.dropped == 0, "потерь нет")

# ---------------------------------------------------------------------------
print("\n[3] ГЛАВНОЕ: пакет догнал предыдущего -- склейки НЕ происходит")
#
# Второй T2 приходит до t2 первого. Если автомат просто ждал бы t2, он взял бы
# t2 ВТОРОГО пакета и склеил с T2 первого. Проверяем, что вместо этого
# измерение отбрасывается.
f = StampFsm()
f.tick(100, T2=True)          # пакет A вошёл
f.tick(105, T2=True)          # пакет B догнал -- A порван
f.tick(145, t2=True)          # это t2 пакета B
f.tick(155, t1=True)
f.tick(195, T1=True)
check(f.dropped == 1, "порванное измерение засчитано")
check(len(f.out) == 1, "готово одно измерение (пакет B)")
check(f.out[0] == (105, 145, 155, 195), "метки ВСЕ от пакета B, склейки нет")
check(consistent(f.out[0]), "согласовано")

# ---------------------------------------------------------------------------
print("\n[4] T2 и T1 в одном такте: следующий пакет не теряется")
#
# Реальная ситуация при потоке: наш ответ выходит, и в тот же такт входит
# следующий запрос. Если не подхватить T2, измерение следующего пакета
# пропадёт целиком.
f = StampFsm()
f.tick(100, T2=True)
f.tick(140, t2=True)
f.tick(150, t1=True)
f.tick(190, T1=True, T2=True)   # ответ ушёл, следующий запрос вошёл
check(len(f.out) == 1, "первое измерение закрыто")
check(f.out[0] == (100, 140, 150, 190), "его метки целы")
check(f.st == WAIT_t2, "автомат УЖЕ ждёт t2 следующего пакета")
check(f.T2 == 190, "T2 следующего подхвачен, не потерян")
check(f.dropped == 0, "это НЕ обрыв -- ничего не засчитано")
# и следующий доходит до конца
f.tick(230, t2=True)
f.tick(240, t1=True)
f.tick(280, T1=True)
check(len(f.out) == 2, "второе измерение тоже готово")
check(f.out[1] == (190, 230, 240, 280), "метки второго верны")

# ---------------------------------------------------------------------------
print("\n[5] метки без начала игнорируются")
#
# t1 или T1 без предшествующего T2 -- от пакета, чей T2 фильтр не узнал.
# Автомат в WAIT_T2 их не видит вовсе.
f = StampFsm()
f.tick(100, t2=True)
f.tick(110, t1=True)
f.tick(120, T1=True)
check(len(f.out) == 0, "ни одного измерения не выдано")
check(f.dropped == 0, "и обрывом это не считается -- начала не было")
check(f.st == WAIT_T2, "автомат на месте")

# ---------------------------------------------------------------------------
print("\n[6] обрыв на поздней стадии")
f = StampFsm()
f.tick(100, T2=True)
f.tick(140, t2=True)
f.tick(150, t1=True)
# T1 не пришёл (например, стек не отправил), зато вошёл следующий запрос
f.tick(300, T2=True)
check(f.dropped == 1, "обрыв в WAIT_T1 засчитан")
check(len(f.out) == 0, "неполное измерение НЕ выдано")
check(f.T2 == 300 and f.st == WAIT_t2, "начали новое с нового T2")

# ---------------------------------------------------------------------------
print("\n[7] переполнение счётчика тактов")
#
# 32 бита при 165 МГц -- 26 секунд. Разность по модулю 2^32 верна и через
# переход, поэтому измерение на границе должно остаться корректным.
M = 1 << 32
f = StampFsm()
f.tick((M - 20) % M, T2=True)
f.tick((M - 20 + 40) % M, t2=True)   # уже за нулём
f.tick((M - 20 + 50) % M, t1=True)
f.tick((M - 20 + 90) % M, T1=True)
T2, t2, t1, T1 = f.out[0]
d_total = (T1 - T2) % M
d_sum = ((t2 - T2) % M) + ((t1 - t2) % M) + ((T1 - t1) % M)
check(d_total == 90, "полный интервал 90 тактов, несмотря на переход через ноль")
check(d_sum == d_total, "сумма интервалов сходится по модулю 2^32")

# ---------------------------------------------------------------------------
print("\n[8] реальный сценарий: 100 пакетов, часть с обрывами")
f = StampFsm()
clk = 10000
for i in range(100):
    f.tick(clk, T2=True); clk += 40
    if i % 17 == 16:
        # каждый 17-й обрывается: следующий запрос догоняет
        continue
    f.tick(clk, t2=True); clk += 10
    f.tick(clk, t1=True); clk += 40
    f.tick(clk, T1=True); clk += 200
good = len(f.out)
print(f"      готово {good}, порвано {f.dropped}")
check(good + f.dropped >= 99, "все пакеты учтены: либо измерены, либо порваны")
check(all(consistent(m) for m in f.out), "все ГОТОВЫЕ измерения согласованы")
# ни одно готовое измерение не должно иметь отрицательных дельт
bad = [m for m in f.out if not (m[0] < m[1] < m[2] < m[3])]
check(not bad, "во всех измерениях метки строго возрастают")

# ---------------------------------------------------------------------------
print("\n=== Итог: " + ("ВСЕ ПРОВЕРКИ ПРОШЛИ" if fails == 0
                        else "ОТКАЗОВ: %d" % fails) + " ===")
sys.exit(1 if fails else 0)
