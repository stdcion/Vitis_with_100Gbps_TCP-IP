#!/usr/bin/env python3
# =============================================================================
# test_axi_read.py -- протокол чтения FIFO хостом
# =============================================================================
#
# ЗАЧЕМ ОТДЕЛЬНО ОТ test_lat_fifo.py. Тот проверяет ЛОГИКУ FIFO: указатели,
# счётчик, переполнение. Здесь -- ПРОТОКОЛ: как хост вычитывает данные и что
# видит регистр на выходе памяти.
#
# Появился по прямому запросу: "можешь просмотреть, что fifo рабочее, мы
# просто никогда так не читали ещё". И действительно нашёл дефект -- но не
# здесь, а в самом .v: первая версия делала
#
#     assign rd_data = mem[rd_ptr];        // асинхронное чтение
#     mem[wr_ptr+0] <= ...; mem[wr_ptr+1] <= ...;   // четыре записи за такт
#
# Пять портов к одному массиву. BRAM даёт два порта и СИНХРОННОЕ чтение,
# distributed RAM -- один порт записи. Vivado либо размножил бы массив в
# четыре копии (512x32 на LUT -- сотни LUT вместо одной BRAM-плитки), либо
# отказал. Исправлено: приём в регистр за такт, выгрузка по слову, чтение
# через регистр rd_data_q.
#
# ЧТО ЭТОТ ТЕСТ ПРОВЕРЯЕТ: успевает ли rd_data_q обновиться между pop и
# следующим чтением. По JTAG между транзакциями миллисекунды, то есть сотни
# тысяч тактов -- запас огромный, но цена ошибки высока: сдвинутые на одно
# слово данные выглядят правдоподобно (те же числа, другой порядок).
#
# ЗАПУСК:  python3 test_axi_read.py

DEPTH = 512

class Fifo:
    def __init__(s):
        s.mem=[0]*DEPTH; s.wr=0; s.rd=0; s.cnt=0
        s.rd_data_q = 0          # регистр на выходе памяти
    def load(s, words):
        for w in words:
            s.mem[s.wr]=w; s.wr=(s.wr+1)%DEPTH; s.cnt+=1
        s.rd_data_q = s.mem[s.rd]        # как после первого такта
    def tick(s, pop=False):
        # ВАЖЕН ПОРЯДОК: rd_data_q берёт mem[rd_ptr] ДО сдвига (неблокирующее)
        new_q = s.mem[s.rd]
        if pop and s.cnt>0:
            s.rd=(s.rd+1)%DEPTH; s.cnt-=1
        s.rd_data_q = new_q

fails=0
def check(c,w):
    global fails
    print(("  [ OK ] " if c else "  [FAIL] ")+w)
    if not c: fails+=1

print("[A] последовательность как в pp_raw: read, pop, read, pop, ...")
#
# pp_raw делает: axi_read32(FIFO_RD); axi_write32(FIFO_POP,1); и так 4 раза.
# Между этими двумя транзакциями по JTAG проходят ТЫСЯЧИ тактов, поэтому
# rd_data_q успевает обновиться много раз. Модель это воспроизводит: после
# каждого pop даём такт.
f=Fifo(); f.load([0xAA,0xBB,0xCC,0xDD, 0x11,0x22,0x33,0x44])
got=[]
for _ in range(8):
    got.append(f.rd_data_q)      # axi_read32
    f.tick(pop=True)             # axi_write32(POP)
    f.tick()                     # такты между JTAG-транзакциями
check(got==[0xAA,0xBB,0xCC,0xDD,0x11,0x22,0x33,0x44],
      f"вычитано по порядку: {[hex(x) for x in got]}")

print("\n[B] ЧТЕНИЕ СРАЗУ ПОСЛЕ pop, БЕЗ ПАУЗЫ -- худший случай")
#
# Если бы хост успел прочитать в СЛЕДУЮЩЕМ такте после pop, он получил бы
# старое значение: rd_data_q обновляется через такт. По JTAG это невозможно
# (транзакция занимает миллисекунды), но проверяем, чтобы знать цену.
f=Fifo(); f.load([0xAA,0xBB,0xCC,0xDD])
v1=f.rd_data_q
f.tick(pop=True)                 # pop, БЕЗ дополнительного такта
v2=f.rd_data_q
check(v1==0xAA, "первое чтение верное")
check(v2==0xAA, "чтение в ТОТ ЖЕ такт после pop даёт СТАРОЕ -- ожидаемо")
f.tick()
check(f.rd_data_q==0xBB, "через один такт значение обновилось")

print("\n[C] запись в FIFO во время чтения хостом")
#
# Пакеты продолжают идти, пока хост читает. Проверяем, что чтение не сбивается.
f=Fifo(); f.load([1,2,3,4])
got=[]
for i in range(4):
    got.append(f.rd_data_q)
    f.tick(pop=True)
    # в этот момент выгружается новое измерение -- пишем слово
    f.mem[f.wr]=0xF0+i; f.wr=(f.wr+1)%DEPTH; f.cnt+=1
    f.tick()
check(got==[1,2,3,4], f"старые данные вычитаны верно: {got}")
check(f.cnt==4, "новые четыре слова на месте")

print("\n=== Итог: "+("ВСЕ ПРОВЕРКИ ПРОШЛИ" if fails==0 else f"ОТКАЗОВ: {fails}")+" ===")
import sys; sys.exit(1 if fails else 0)
