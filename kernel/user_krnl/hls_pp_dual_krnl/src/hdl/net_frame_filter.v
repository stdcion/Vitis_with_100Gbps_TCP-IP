// =============================================================================
// net_frame_filter -- «наш кадр или служебный», по числу слов на шине
// =============================================================================
//
// ЗАЧЕМ. На axis_net_* идёт ВЕСЬ трафик стека, а не только наш TCP-кадр.
// Проверено по коду network_stack.sv:
//
//     ICMP ─┐
//     UDP  ─┤
//     TOE  ─┼→ ip_merger (4to1) → mac_ip_encode ─┐
//     RoCE ─┘        (:459)            (:520)     ├→ arp_merger (2to1) → axis_net_tx
//                         ARP ────────────────────┘        (:556)
//
// Наш кадр там ничем не выделен, поэтому «первый beat после события» ловит не
// тот кадр с высокой вероятностью. Внутри окна замера (~660 тактов) реально
// уходят два вида чужих кадров:
//
//   * ARP-запрос -- mac_ip_encode при отправке делает arp_lookup_request, и если
//     записи в таблице нет, ARP уходит ПРЯМО ПЕРЕД нашим TCP-пакетом;
//   * чистый ACK от TOE -- эхо отвечает данными, но TOE отдельно подтверждает
//     пришедший запрос, и этот ACK уходит через единицы-десятки тактов.
//
// Ранняя оценка «чужой трафик не попадает в окно» была НЕВЕРНА: она исходила из
// задержки отложенного ACK (TIME_64us ≈ 10500 тактов), что верно только для ACK
// ПРЕДЫДУЩЕГО замера.
//
// КАК РАЗЛИЧАЕМ. Считать длину по tkeep не нужно: на 512-битной шине разница
// видна по числу слов.
//
//     чистый ACK          54 байта        1 слово
//     ARP                 42-60           1
//     ICMP echo reply     42+             1
//     наш кадр msg=64     14+20+20+64=118 2
//     наш кадр msg=256    310             5
//
// Служебный трафик укладывается в ОДНО слово, наш кадр при msgBytes>=32 занимает
// два и больше. Значит достаточно счётчика слов в кадре: одно сравнение против
// трёх, и дешевле, чем popcount(tkeep).
//
// ВТОРОЙ ПРИЗНАК: МАРКЕР В PAYLOAD. Одной длины НЕ ХВАТАЕТ, и это не
// теоретическое опасение -- TCP SYN с опциями (MSS, SACK, WS) занимает 74 байта,
// то есть ТОЖЕ два слова, и от нашего кадра при msgBytes=64 по длине не
// отличается. Поэтому ядро кладёт в payload константу, а фильтр её сверяет.
//
// ГДЕ ОНА ЛЕЖИТ НА ПРОВОДЕ. Заголовки перед payload -- Ethernet 14 + IP 20 +
// TCP 20 = 54 байта, и это ФИКСИРОВАННО: опции TCP стек добавляет только в SYN
// (TCP_HEADER_SIZE=160 бит против TCP_OPTIONAL_HEADER_SIZE=320,
// toe_internals.hpp:426-427), у кадров с данными заголовок ровно 20 байт.
// Значит payload[k] попадает на байт 54+k кадра, и маркер payload[4..9] -- на
// байты 58..63, то есть на биты 464..511 ПЕРВОГО 512-битного слова. При любом
// msgBytes: смещение задано заголовками, а не размером сообщения.
//
// Это и делает признак дешёвым: ОДНО сравнение на фиксированном смещении, без
// разбора EtherType/proto/порта и без поиска по tkeep. Разбор заголовка (как
// резервный вариант в latency_net_probe_design.md) потребовал бы трёх сравнений
// и спотыкался бы о порт: на RX-канале dst_port -- это эфемерный порт клиента,
// который выбирает TOE и хост не знает.
//
// ПОЧЕМУ payload[4..9], А НЕ payload[0..3]. Первые четыре байта заняты номером
// отправки (`sent`), он меняется каждый замер -- как константу его не сравнить.
//
// ПОЧЕМУ НУЖНЫ ОБА ПРИЗНАКА, А НЕ ОДИН. Они закрывают РАЗНЫЕ дырки:
//
//   * односоловные кадры (чистый ACK 54 б, ARP 42-60, ICMP 42) отсекает ДЛИНА.
//     Маркер на них читать нельзя вообще: биты 464..511 у них за tkeep, то есть
//     мусор или паддинг, и сравнение с ним бессмысленно;
//   * SYN с опциями отсекает МАРКЕР: длину он проходит (два слова), но на битах
//     464..511 у него опции MSS/SACK/WS, а не наша константа.
//
// ЧЕГО НЕ ОТЛИЧАЕТ ДАЖЕ ПАРА: ретрансмит нашего же пакета -- та же длина, тот же
// маркер, тот же порт. Но ретрансмит означает потерю, её видно по timeoutCount,
// и такой замер и так уходит в discarded.
//
// ОБРАТНЫЙ ПУТЬ. Эхо отражает payload дословно (payload[wordIdx] из принятого,
// hls_echo_probe_dual_krnl.cpp, состояние TX), поэтому маркер тот же в обе
// стороны -- одна константа на все четыре инстанса.
//
// РЕГИСТРА В ТРАКТЕ НЕТ. tdata/tvalid/tready идут насквозь в обёртке, этот
// модуль только СМОТРИТ на три бита управления. Поэтому измеряемый путь не
// удлиняется -- что важно, потому что мы им же и меряем: регистр добавил бы
// такт (6 нс) ровно в ту величину, которую вычисляем.
// =============================================================================

`timescale 1ns / 1ps
`default_nettype none

module net_frame_filter #(
     // Маркер в payload[4..9]. Должен совпадать с константой, которую пишет
     // ядро (hls_echo_probe_dual_krnl.cpp, состояние SEND_DATA). Параметр, а не
     // localparam, чтобы значение стояло в одном месте на все четыре инстанса.
     parameter [47:0] EPD_MARKER = 48'h5A3C96E1B7D2
)(
     input  wire         ap_clk,
     input  wire         ap_rst_n,

     // подсматриваем шину (не влияем на неё)
     input  wire         tvalid,
     input  wire         tready,
     input  wire         tlast,
     input  wire [511:0] tdata,

     input  wire [31:0]  min_words,    // порог из регистра хоста

     output wire         frame_ours,   // строб: последнее слово НАШЕГО кадра
     output reg  [31:0]  count_ours,   // прошло фильтр
     output reg  [31:0]  count_drop    // отсеяно (ARP/ACK/ICMP/SYN)
);

     // tready ОБЯЗАТЕЛЕН: без него считается предъявление, а не передача, и при
     // backpressure счёт слов уедет вместе с таймстемпом.
     wire beat = tvalid & tready;

     // Слов в текущем кадре (до последнего). 6 бит хватает на 64 слова = 4 КБ,
     // столько же, сколько EPD_MAX_WORDS в ядре.
     reg [5:0] words;

     always @(posedge ap_clk) begin
          if (~ap_rst_n)      words <= 6'd0;
          else if (beat)      words <= tlast ? 6'd0 : (words + 6'd1);
     end

     // На последнем слове число слов кадра = words+1. Сравниваем с порогом.
     //
     // Порог берём как min_words[6:0]: 7 бит, чтобы сравнение не переполнялось
     // на frame_words. Если хост запишет больше 127, старшие биты отсекутся --
     // но при EPD_MAX_WORDS=64 такое значение и так вне рабочего диапазона, а
     // epd_configure считает порог сам по msgBytes.
     wire [6:0] frame_words = {1'b0, words} + 7'd1;
     wire       len_ok      = (frame_words >= min_words[6:0]);

     // ── маркер: сверяется на ПЕРВОМ слове кадра, решение держится до tlast ──
     //
     // Регистр здесь не в тракте данных, а рядом с ним: tdata идёт насквозь
     // (passthrough в обёртке), а этот триггер лишь запоминает решение,
     // принятое на первом слове, чтобы выдать строб на последнем. Задержки в
     // измеряемый путь это не добавляет.
     //
     // Сравнение на первом слове, а не на последнем, -- не оптимизация, а
     // единственный вариант: маркер физически лежит в первом слове (payload[4..9]
     // на байтах 58..63 кадра), а строб нужен на последнем, чтобы измерение не
     // зависело от размера сообщения. Между ними и стоит этот регистр.
     wire first_word  = beat & (words == 6'd0);
     wire marker_here = (tdata[511:464] == EPD_MARKER);

     reg marker_seen;
     always @(posedge ap_clk) begin
          if (~ap_rst_n)        marker_seen <= 1'b0;
          else if (first_word)  marker_seen <= marker_here;
     end

     // ОДНОСЛОВНЫЙ КАДР -- ОТДЕЛЬНЫЙ СЛУЧАЙ, И ЕГО НАДО РАЗОБРАТЬ ЯВНО.
     //
     // Если кадр укладывается в одно слово, first_word и tlast приходятся на
     // ОДИН такт. Регистр marker_seen к этому моменту ещё держит значение от
     // ПРЕДЫДУЩЕГО кадра -- он обновится только по фронту. То есть решение о
     // текущем кадре было бы принято по чужому маркеру.
     //
     // На практике такой кадр отсекает длина (len_ok ложен при minWords>=2), и
     // соблазн положиться на это велик. Но тогда корректность фильтра зависела
     // бы от того, что хост записал разумный порог: при minWords=1 или 0
     // односоловные ACK начали бы проходить или не проходить в зависимости от
     // маркера СОСЕДНЕГО кадра -- то есть недетерминированно, редко и
     // невоспроизводимо. Худший вид дефекта, и ровно тот, от которого мы уже
     // защищались сбросом minWords в 2, а не в 0.
     //
     // Поэтому на последнем слове маркер берётся из ПРАВИЛЬНОГО источника: с
     // шины напрямую, если кадр односоловный, и из регистра иначе.
     wire single_word = tlast & (words == 6'd0);
     wire marker_ok   = single_word ? marker_here : marker_seen;

     // Два признака через И -- они закрывают РАЗНЫЕ дырки (см. шапку):
     // длина отсекает ACK/ARP/ICMP, маркер отсекает SYN с опциями.
     wire is_ours = len_ok & marker_ok;

     assign frame_ours = beat & tlast & is_ours;

     // Пара счётчиков «прошло / отсеяно» -- она важнее, чем кажется. Если Drop
     // растёт, а Count нет, значит фильтр режет ВСЁ, включая наш кадр (например,
     // min_words завышен). Без этой пары «таймстемп не обновился» не отличить от
     // «фильтр слишком строгий», а без Count -- ещё и от «врезка подключена не
     // туда». Та же логика, по которой в ядре появились listenAttempts и
     // portState.
     always @(posedge ap_clk) begin
          if (~ap_rst_n) begin
               count_ours <= 32'd0;
               count_drop <= 32'd0;
          end else if (beat & tlast) begin
               if (is_ours) count_ours <= count_ours + 32'd1;
               else         count_drop <= count_drop + 32'd1;
          end
     end

endmodule

`default_nettype wire
