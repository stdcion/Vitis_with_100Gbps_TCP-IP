// =============================================================================
// stub_vio_dual_echo_dbg -- заглушка отладочного VIO для симуляции
// =============================================================================
//
// ЗАЧЕМ. Обёртка инстанцирует vio_dual_echo_dbg -- Vivado IP, который
// существует только в собранном проекте (создаётся в
// package_hls_dual_echo_krnl.tcl). В xsim его нет, и без заглушки элаборация
// падает:
//
//     ERROR: [VRFC 10-2063] Module <vio_dual_echo_dbg> not found
//
// Порты повторяют инстанс в hls_dual_echo_krnl_wrapper.sv:350-360 -- один clk и
// восемь probe_in. Разрядности: probe_in0..3 по 32 бита, probe_in4..7 по одному.
//
// ЛОГИКИ НЕТ И БЫТЬ НЕ ДОЛЖНО. VIO только наблюдает: он не влияет на дизайн, и
// заглушка обязана быть такой же пассивной, иначе тест проверял бы не тот
// дизайн, который уходит в битстрим. Все входы намеренно не используются.
// =============================================================================

`timescale 1ns / 1ps

module vio_dual_echo_dbg (
     input  wire        clk,
     input  wire [31:0] probe_in0,
     input  wire [31:0] probe_in1,
     input  wire [31:0] probe_in2,
     input  wire [31:0] probe_in3,
     input  wire        probe_in4,
     input  wire        probe_in5,
     input  wire        probe_in6,
     input  wire        probe_in7
);

// Пусто по построению -- см. шапку.

endmodule
